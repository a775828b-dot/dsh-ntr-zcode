import assert from 'node:assert/strict';
import { setTimeout as delay } from 'node:timers/promises';

export async function queueFlow({ desktop, mobile, seed, imageBytes }) {
  const stop = mobile.getByRole('button', { name: '停止生成', exact: true });
  const history = async () => (await desktop.evaluate(async id => (await fetch(`/api/plugins/ntr-test/history?sessionId=${encodeURIComponent(id)}`)).json(), seed.sessionId)).first.value;
  const items = async () => (await history()).projections.values.inbox?.['next-turn'] ?? [];
  const rows = mobile.locator('li[data-queue-item-id]');
  const row = text => rows.filter({ hasText: text });
  const waitFor = async check => { for (let i = 0; i < 60; i++) { if (await check()) return; await delay(250); } throw new Error('Queue assertion timed out'); };
  const send = async text => {
    await mobile.locator('[contenteditable=true]').first().fill(text);
    const button = mobile.getByRole('button', { name: /^(发送|加入队列)$/ });
    await button.click(); await delay(800);
  };
  const queuedTexts = async () => (await items()).map(m => m.content.filter(b => b.type === 'text').map(b => b.text).join(''));
  const turnFor = (records, text) => {
    let turn;
    for (const { event } of records) {
      if (event?.type === 'turn/start') turn = event.data.turn;
      if (event?.type === 'user/message' && event.data.content.some(b => b.type === 'text' && b.text === text)) return turn;
    }
    throw new Error(`Missing consumed input: ${text}`);
  };
  const drag = async (from, to) => {
    const a = await row(from).locator('[data-v4-queue-drag-handle]').boundingBox();
    const b = await row(to).locator('[data-v4-queue-drag-handle]').boundingBox();
    assert(a && b);
    await mobile.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
    await mobile.mouse.down();
    await mobile.mouse.move(a.x + a.width / 2 + 8, a.y + a.height / 2, { steps: 4 });
    await mobile.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 20 });
    await delay(300); await mobile.mouse.up(); await delay(1000);
  };
  await stop.waitFor({ state: 'hidden' });
  await send('NTR queue blocking turn'); await stop.waitFor();
  await send('NTR queued A'); await send('NTR queued B');
  await mobile.locator('input[type=file]').first().setInputFiles({ name: 'queued-image.png', mimeType: 'image/png', buffer: imageBytes ?? await mobile.screenshot() });
  await delay(1500);
  await send('NTR queued C');
  await waitFor(async () => (await items()).length === 3);
  const original = await items();
  await drag('NTR queued C', 'NTR queued A');
  assert.deepEqual(await queuedTexts(), ['NTR queued C', 'NTR queued A', 'NTR queued B']);
  assert.deepEqual((await items())[0], original[2]);
  console.log('PASS_QUEUE_MOBILE_DRAG_AND_ATTACHMENTS');
  await mobile.setViewportSize({ width: 1440, height: 960 }); await delay(800);
  await drag('NTR queued C', 'NTR queued B');
  assert.deepEqual(await queuedTexts(), ['NTR queued A', 'NTR queued B', 'NTR queued C']);
  await drag('NTR queued C', 'NTR queued A');
  assert.deepEqual(await queuedTexts(), ['NTR queued C', 'NTR queued A', 'NTR queued B']);
  console.log('PASS_QUEUE_DESKTOP_DRAG_BOTH_DIRECTIONS');
  await mobile.setViewportSize({ width: 390, height: 844 }); await delay(500);
  await stop.click(); await stop.waitFor({ state: 'hidden' });
  await mobile.locator('[data-queue-auto-drain=false]').waitFor();
  await delay(1500); assert.equal((await items()).length, 3);
  await mobile.reload({ waitUntil: 'domcontentloaded' });
  await mobile.locator('[data-queue-auto-drain=false]').waitFor({ timeout: 15000 });
  assert.deepEqual(await queuedTexts(), ['NTR queued C', 'NTR queued A', 'NTR queued B']);
  await mobile.screenshot({ path: 'test/queue-paused-mobile.png', fullPage: true });
  console.log('PASS_QUEUE_STOP_PAUSE_AND_BROWSER_RELOAD');
  await row('NTR queued B').getByRole('button', { name: /^(立即|立即发送)$/ }).click();
  await mobile.getByText('Queue drained A.', { exact: true }).waitFor({ timeout: 20000 });
  await stop.waitFor({ state: 'hidden' });
  assert.equal((await items()).length, 0);
  const messages = (await history()).records.filter(r => r.event?.type === 'user/message').map(r => r.event.data);
  const delivered = messages.filter(m => m.content.some(b => b.type === 'text' && /^NTR queued [ABC]$/.test(b.text)));
  assert.deepEqual(delivered.map(m => m.content.find(b => b.type === 'text').text), ['NTR queued B', 'NTR queued C', 'NTR queued A']);
  assert.equal(new Set(delivered.map(m => m.id)).size, 3);
  assert.deepEqual(delivered[1].content, original[2].content);
  console.log('PASS_QUEUE_PROMOTE_EXACTLY_ONCE_AND_DRAIN_ORDER');
  await send('NTR slow running turn'); await stop.waitFor();
  await send('NTR queued D'); await send('NTR queued E');
  const policy = await desktop.evaluate(async sessionId => (await fetch('/api/plugins/ntr-test/queue-policy', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, autoDrain: false }) })).json(), seed.sessionId);
  assert.equal(policy.status, 'accepted');
  await mobile.getByText(/Queue slow current.*complete\./).waitFor({ timeout: 20000 });
  await stop.waitFor({ state: 'hidden', timeout: 15000 });
  await delay(1200);
  assert.deepEqual(await queuedTexts(), ['NTR queued D', 'NTR queued E']);
  const paused = await history(), slowTurn = turnFor(paused.records, 'NTR slow running turn');
  assert.equal(paused.records.find(r => r.event?.type === 'turn/end' && r.event.data.turn === slowTurn)?.event.data.reason.kind, 'completed');
  console.log('PASS_QUEUE_PAUSE_WITHOUT_INTERRUPTING_CURRENT_REPLY');
  await mobile.getByRole('button', { name: /恢复.*队列|继续.*队列/ }).click();
  await mobile.getByText('Queue resumed E.', { exact: true }).waitFor({ timeout: 20000 });
  await stop.waitFor({ state: 'hidden' }); assert.equal((await items()).length, 0);
  console.log('PASS_QUEUE_RESUME_BUTTON');
  await send('NTR immediate blocking turn'); await stop.waitFor();
  await send('NTR queued G'); await send('NTR queued F');
  await row('NTR queued F').getByRole('button', { name: /^(立即|立即发送)$/ }).click();
  await mobile.getByText('Queue after F G.', { exact: true }).waitFor({ timeout: 20000 });
  await stop.waitFor({ state: 'hidden' });
  const final = await history();
  const ends = final.records.filter(r => r.event?.type === 'turn/end');
  const interruptedTurn = turnFor(final.records, 'NTR immediate blocking turn');
  assert.equal(ends.find(r => r.event.data.turn === interruptedTurn)?.event.data.reason.kind, 'aborted');
  assert(turnFor(final.records, 'NTR queued F') > interruptedTurn);
  const actual = final.records.filter(r => r.event?.type === 'user/message').map(r => r.event.data.content.find(b => b.type === 'text')?.text).filter(t => /^NTR queued [FG]$/.test(t ?? ''));
  assert.deepEqual(actual, ['NTR queued F', 'NTR queued G']);
  assert.equal((await items()).length, 0);
  console.log('PASS_QUEUE_IMMEDIATE_INTERRUPTS_RUNNING_NOT_STEERING');
  await mobile.reload({ waitUntil: 'domcontentloaded' });
  await mobile.getByText('Queue after F G.', { exact: true }).waitFor({ timeout: 15000 });
  const previewButton = mobile.getByRole('button', { name: '打开图片预览', exact: true }).first();
  await previewButton.scrollIntoViewIfNeeded();
  await previewButton.click();
  const preview = mobile.getByRole('dialog', { name: 'queued-image.png', exact: true });
  await preview.waitFor();
  await waitFor(async () => preview.locator('img').first().evaluate(img => img.complete && img.naturalWidth > 0));
  await preview.getByRole('button', { name: '关闭', exact: true }).click();
  console.log('PASS_QUEUE_IMAGE_HISTORY_PREVIEW_AFTER_RELOAD');
  await mobile.screenshot({ path: 'test/queue-completed-mobile.png', fullPage: true });
}
