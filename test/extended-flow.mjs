import assert from 'node:assert/strict';
import { setTimeout as delay } from 'node:timers/promises';

export async function extendedFlow({ desktop, mobile, seed }) {
  const inspect = async label => { if (process.env.NTR_VERBOSE) console.log(label, await mobile.locator('body').ariaSnapshot()); };
  const history = () => desktop.evaluate(async id => (await fetch(`/api/plugins/ntr-test/history?sessionId=${encodeURIComponent(id)}`)).json(), seed.sessionId);
  const directory = () => desktop.evaluate(async () => (await fetch('/api/plugins/ntr-test/directory')).json());
  await mobile.getByRole('button', { name: '停止生成', exact: true }).waitFor({ state: 'hidden', timeout: 15000 });
  await mobile.locator('[contenteditable=true]').first().fill('NTR extended wait');
  await mobile.getByRole('button', { name: '发送', exact: true }).click();
  await mobile.getByRole('button', { name: '停止生成', exact: true }).waitFor({ timeout: 15000 });
  await delay(1500);
  for (const answer of ['Allow once', 'Reject']) {
    const interaction = await desktop.evaluate(async sessionId => (await fetch('/api/plugins/ntr-test/interaction', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, kind: 'permission' }) })).json(), seed.sessionId);
    await delay(2000);
    await inspect('APPROVAL_UI');
    await mobile.getByRole('option', { name: answer === 'Reject' ? '拒绝' : '允许', exact: true }).click({ timeout: 10000 });
    await mobile.getByRole('button', { name: '确认', exact: true }).click();
    await delay(1200);
    const result = await desktop.evaluate(async () => (await fetch('/api/plugins/ntr-test/interaction')).json());
    assert.equal(result[interaction.id]?.value, answer === 'Reject' ? 'rejected' : 'allowed-once');
    console.log('PASS_APPROVAL', answer);
  }
  const question = await desktop.evaluate(async sessionId => (await fetch('/api/plugins/ntr-test/interaction', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, kind: 'question' }) })).json(), seed.sessionId);
  await delay(2000);
  await inspect('QUESTION_UI');
  await mobile.screenshot({ path: 'test/extended-question.png', fullPage: true });
  // Selectors intentionally use the original page's accessible human controls.
  await mobile.getByText('Blue', { exact: true }).click();
  await inspect('QUESTION_NOTE_UI');
  await mobile.locator('textarea').last().fill('NTR mobile note');
  await mobile.getByRole('button', { name: /提交|确认|Submit/ }).last().click();
  await delay(1500);
  const answers = await desktop.evaluate(async () => (await fetch('/api/plugins/ntr-test/interaction')).json());
  assert.deepEqual(answers[question.id]?.value, { answers: [{ id: 'choice', selected: ['Blue'] }, { id: 'note', selected: [], custom: 'NTR mobile note' }] });
  console.log('PASS_QUESTION');
  await mobile.locator('[contenteditable=true]').first().fill('NTR queued item');
  await inspect('QUEUE_SEND_UI');
  await mobile.getByRole('button', { name: '加入队列', exact: true }).click();
  await delay(1500);
  await inspect('QUEUE_UI');
  assert((await history()).first.value.projections.values.inbox['next-turn'].some(m => m.content.some(b => b.text === 'NTR queued item')));
  await mobile.screenshot({ path: 'test/extended-queue.png', fullPage: true });
  console.log('PASS_QUEUE_ADMISSION');
  await mobile.getByRole('button', { name: /编辑/ }).last().click();
  await delay(1200);
  assert.equal((await history()).first.value.projections.values.inbox['next-turn'].length, 0);
  await mobile.locator('[contenteditable=true]').first().fill('NTR edited queue');
  await mobile.getByRole('button', { name: '加入队列', exact: true }).click();
  await delay(1200);
  await inspect('QUEUE_EDIT_UI');
  await mobile.getByRole('button', { name: /移除|删除/ }).last().click();
  await delay(1200);
  assert.equal((await history()).first.value.projections.values.inbox['next-turn'].length, 0);
  console.log('PASS_QUEUE_EDIT_DELETE');
  await mobile.getByRole('button', { name: '停止生成', exact: true }).click();
  await mobile.getByRole('button', { name: '停止生成', exact: true }).waitFor({ state: 'hidden', timeout: 15000 });
  await mobile.locator('input[type=file]').first().setInputFiles({ name: 'ntr-notes.txt', mimeType: 'text/plain', buffer: Buffer.from('NTR ordinary file fixture') });
  await delay(1500);
  await mobile.locator('[contenteditable=true]').first().fill('NTR file upload');
  await mobile.getByRole('button', { name: '发送', exact: true }).click();
  await mobile.getByRole('button', { name: '停止生成', exact: true }).waitFor({ state: 'hidden', timeout: 20000 });
  await delay(1800);
  const fileHistory = await history();
  assert(fileHistory.first.value.records.some(r => r.event?.type === 'user/message' && r.event.data.content.some(b => b.type === 'file' && b.attachment.name === 'ntr-notes.txt')));
  console.log('PASS_FILE_UPLOAD_DURABLE');
  const beforeFork = (await directory()).sessions.length;
  await mobile.getByRole('button', { name: '分叉', exact: true }).first().click();
  await delay(2000);
  await inspect('FORK_UI');
  assert((await directory()).sessions.length > beforeFork);
  console.log('PASS_FORK');
  await mobile.getByRole('button', { name: '返回任务首页', exact: true }).click();
  await delay(2000);
  await inspect('INDEX_UI');
  await mobile.screenshot({ path: 'test/extended-index.png', fullPage: true });
  await desktop.evaluate(async sessionId => fetch('/api/plugins/ntr-test/rename', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, title: 'NTR Original Live Rename' }) }), seed.sessionId);
  await mobile.getByRole('button', { name: /^NTR Original Live Rename/ }).waitFor({ timeout: 10000 });
  console.log('PASS_LIVE_INDEX_RENAME');
  await mobile.getByRole('button', { name: /^NTR Original Live Rename/ }).click();
  await mobile.locator('[contenteditable=true]').first().waitFor({ timeout: 10000 });
  await mobile.getByText('NTR file upload', { exact: true }).waitFor({ timeout: 15000 });
  await delay(1500);
  await mobile.getByRole('button', { name: '切换模式', exact: true }).click();
  await mobile.getByRole('menuitemcheckbox').click();
  await mobile.locator('[contenteditable=true]').first().fill('NTR plan verification');
  await mobile.getByRole('button', { name: '发送', exact: true }).click();
  await mobile.getByText('NTR plan and tool completed.', { exact: true }).waitFor({ timeout: 25000 });
  assert.equal((await history()).first.value.projections.values.plan.active, true);
  assert.equal((await history()).first.value.projections.values.todos.length, 2);
  console.log('PLAN_TOOL_UI', await mobile.locator('body').ariaSnapshot());
  await mobile.screenshot({ path: 'test/extended-plan.png', fullPage: true });
  console.log('PASS_PLAN_AND_TOOL');
  await mobile.getByRole('button', { name: '停止生成', exact: true }).waitFor({ state: 'hidden', timeout: 15000 });
  await mobile.getByRole('button', { name: /取消下一次提交的计划模式|关闭计划模式/ }).click();
  await mobile.locator('[contenteditable=true]').first().fill('/goal NTR isolated goal test');
  await mobile.getByRole('button', { name: '发送', exact: true }).click();
  await delay(3000);
  console.log('GOAL_UI', await mobile.locator('body').ariaSnapshot());
  assert.equal((await history()).first.value.projections.values.goal?.goal.objective, 'NTR isolated goal test');
  console.log('PASS_GOAL_CREATE');
  await mobile.getByRole('button', { name: '展开状态', exact: true }).click();
  console.log('GOAL_PANEL_UI', await mobile.locator('body').ariaSnapshot());
  await mobile.getByRole('button', { name: /暂停目标|暂停/ }).last().click();
  await delay(1500);
  assert.equal((await history()).first.value.projections.values.goal.goal.phase, 'paused');
  console.log('PASS_GOAL_PAUSE');
  const stop = mobile.getByRole('button', { name: '停止生成', exact: true });
  if (await stop.isVisible()) await stop.click();
  await stop.waitFor({ state: 'hidden', timeout: 15000 });
  await mobile.getByRole('button', { name: '继续目标', exact: true }).click();
  await stop.waitFor({ timeout: 15000 });
  assert.equal((await history()).first.value.projections.values.goal.goal.phase, 'active');
  await stop.click();
  await stop.waitFor({ state: 'hidden', timeout: 15000 });
  assert.equal((await history()).first.value.projections.values.goal.goal.phase, 'paused');
  console.log('PASS_GOAL_RESUME_AND_STOP');
  await mobile.setViewportSize({ width: 1440, height: 960 });
  await delay(1500);
  console.log('WIDE_UI', await mobile.locator('body').ariaSnapshot());
  await mobile.screenshot({ path: 'test/extended-wide.png', fullPage: true });
  const row = mobile.locator('[data-web-remote-task-row]').filter({ has: mobile.getByRole('button', { name: '打开任务 NTR Original Live Rename', exact: true }) });
  await row.hover();
  console.log('ROW_UI', await row.ariaSnapshot());
  await row.getByRole('button', { name: '置顶任务', exact: true }).click();
  await delay(2000);
  assert((await directory()).membership.value.pinnedSessionIds.includes(seed.sessionId));
  await desktop.evaluate(async sessionId => fetch('/api/plugins/ntr-test/rename', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, title: 'NTR Pinned Rename' }) }), seed.sessionId);
  await mobile.getByRole('heading', { name: 'NTR Pinned Rename', exact: true }).waitFor({ timeout: 12000 });
  assert((await directory()).membership.value.pinnedSessionIds.includes(seed.sessionId));
  await desktop.evaluate(async sessionId => fetch('/api/plugins/ntr-test/rename', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sessionId, title: 'NTR Original Live Rename' }) }), seed.sessionId);
  await mobile.getByRole('heading', { name: 'NTR Original Live Rename', exact: true }).waitFor({ timeout: 12000 });
  console.log('PASS_PINNED_TITLE_SYNC');
  await row.hover();
  await row.getByRole('button', { name: /取消置顶/ }).click();
  await delay(1500);
  assert(!(await directory()).membership.value.pinnedSessionIds.includes(seed.sessionId));
  console.log('PASS_PIN_UNPIN');
  await row.hover();
  await row.getByRole('button', { name: '归档任务', exact: true }).click();
  await row.getByRole('button', { name: '确认', exact: true }).click();
  await delay(2000);
  assert((await directory()).membership.value.archivedSessionIds.includes(seed.sessionId));
  console.log('PASS_ARCHIVE');
  await mobile.getByRole('button', { name: '归档', exact: true }).click();
  await delay(1500);
  console.log('ARCHIVE_UI', await mobile.locator('body').ariaSnapshot());
  await row.hover();
  await row.getByRole('button', { name: /取消归档|恢复/ }).click();
  await delay(2000);
  assert(!(await directory()).membership.value.archivedSessionIds.includes(seed.sessionId));
  console.log('PASS_UNARCHIVE');
}
